// Generate 24 hours of baseline historical telemetry for charts
export function generateHistoricalTelemetry(well: Well): TelemetryPoint[] {
  const points: TelemetryPoint[] = [];
  const now = Date.now();
  const stepMs = 3600 * 1000; // 1 hour step

  for (let i = 24; i >= 0; i--) {
    const time = new Date(now - i * stepMs).toISOString().substring(11, 16);
    // Add deterministic micro-variations
    const noise = Math.sin(i * 0.7) * 0.04;
    const tempNoise = Math.cos(i * 0.5) * 1.5;

    points.push({
      timestamp: time,
      oilRate: Math.max(0, Math.round((well.oilRate * (1 + noise)) * 10) / 10),
      waterCut: Math.max(5, Math.min(95, Math.round((well.waterCut + noise * 10) * 10) / 10)),
      liquidRate: Math.max(0, Math.round((well.totalLiquidRate * (1 + noise * 0.8)) * 10) / 10),
      reservoirTemp: Math.round((well.reservoirTemp + tempNoise) * 10) / 10,
      reservoirPressure: Math.round((well.reservoirPressure + noise * 2) * 10) / 10,
      viscosity: Math.max(200, Math.round(well.viscosity * (1 - tempNoise * 0.03))),
      steamInjectionRate: well.currentPhase === 'Injection' ? Math.round((well.cssParams.injectionRateTph + noise * 2) * 10) / 10 : 0,
      srpMotorCurrent: Math.round((well.srpParams.motorCurrentAmp + noise * 3) * 10) / 10,
      srpRodLoad: Math.round((well.srpParams.surfaceRodLoadKn + noise * 4) * 10) / 10,
      srpFillage: Math.round((well.srpParams.pumpFillagePct + noise * 5) * 10) / 10,
      steamQuality: well.cssParams.steamQualityPct,
    });
  }

  return points;
}
